pub(crate) const TAURI_DIRECTORY: &str = "apps/desktop/src-tauri";
const CONFIG_FILE: &str = "tauri.conf.json";
const CONFIG_PREFIX: &str = "tauri.";
const CAPABILITIES_DIRECTORY: &str = "capabilities";
const MAIN_CAPABILITY: &str = "main";
const MAIN_CAPABILITY_FILE: &str = "main.json";
const PERMISSIONS_DIRECTORY: &str = "permissions";
const COMMAND_SET_FILE: &str = "commands.toml";
const AUTOGENERATED_DIRECTORY: &str = "autogenerated";
const COMMAND_SET: &str = "commands";
pub(crate) const ALLOWED_PERMISSIONS_FILE: &str =
    "harness/capability-check/allowed-permissions.toml";
pub(crate) const COMMAND_LIST_FILE: &str = "ipc/commands.txt";
const COMMAND_PERMISSION_PREFIX: &str = "allow-";
const PLUGIN_SEPARATOR: char = ':';

pub(crate) const FORBIDDEN_PERMISSIONS: [&str; 12] = [
    "core:default",
    "core:event:default",
    "core:event:allow-emit",
    "core:event:allow-emit-to",
    "shell:*",
    "dialog:*",
    "opener:*",
    "fs:*",
    "http:*",
    "biometric:*",
    "notification:*",
    "autostart:*",
];

#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub(crate) enum Rule {
    NotExplicit,
    ListNotMain,
    MainMissing,
    ExtraCapabilityFile,
    Identifier,
    Windows,
    Remote,
    Forbidden(String),
    NotAllowed,
    HandWrittenCommand,
    CommandSetNotReferenced,
    CommandSetShape,
    CommandMismatch,
    CommandListFormat,
    ExtraPermissionFile,
    BuildHandWrittenCommands,
    BuildNotReadingList,
    ExtraConfig,
    Unparsable,
}

impl fmt::Display for Rule {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let name = match self {
            Self::Forbidden(pattern) => return write!(f, "capability:forbidden:{pattern}"),
            Self::NotExplicit => "not-explicit",
            Self::ListNotMain => "list-not-main",
            Self::MainMissing => "main-missing",
            Self::ExtraCapabilityFile => "extra-capability-file",
            Self::Identifier => "identifier",
            Self::Windows => "windows",
            Self::Remote => "remote",
            Self::NotAllowed => "not-allowed",
            Self::HandWrittenCommand => "hand-written-command",
            Self::CommandSetNotReferenced => "command-set-not-referenced",
            Self::CommandSetShape => "command-set-shape",
            Self::CommandMismatch => "command-mismatch",
            Self::CommandListFormat => "command-list-format",
            Self::ExtraPermissionFile => "extra-permission-file",
            Self::BuildHandWrittenCommands => "build-hand-written-commands",
            Self::BuildNotReadingList => "build-not-reading-list",
            Self::ExtraConfig => "extra-config",
            Self::Unparsable => "unparsable",
        };
        write!(f, "capability:{name}")
    }
}

pub(crate) struct Findings {
    items: BTreeSet<Finding<Rule>>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct AllowedPermissions {
    path: String,
    entries: BTreeSet<String>,
}

impl AllowedPermissions {
    pub(crate) fn new(path: &str, entries: impl IntoIterator<Item = String>) -> Self {
        Self {
            path: String::from(path),
            entries: entries.into_iter().collect(),
        }
    }

    pub(crate) fn load(root: &Path) -> Result<Self, String> {
        let table: toml::Table = read_text(&root.join(ALLOWED_PERMISSIONS_FILE))?
            .parse()
            .map_err(|error| format!("{ALLOWED_PERMISSIONS_FILE}: {error}"))?;
        let reason = table.get("reason").and_then(toml::Value::as_str);
        let entries = table
            .get("permissions")
            .and_then(toml::Value::as_array)
            .and_then(|list| {
                list.iter()
                    .map(|entry| entry.as_str().map(String::from))
                    .collect::<Option<Vec<String>>>()
            });
        match (entries, reason) {
            (Some(listed), Some(why)) if table.len() == 2 && !why.trim().is_empty() => {
                Ok(Self::new(ALLOWED_PERMISSIONS_FILE, listed))
            }
            (Some(_) | None, Some(_) | None) => Err(format!(
                "{ALLOWED_PERMISSIONS_FILE}: reason과 permissions 문자열 목록만 있어야 한다"
            )),
        }
    }

    fn findings(&self, findings: &mut Findings) {
        for entry in &self.entries {
            if let Some(pattern) = forbidden_pattern(entry) {
                findings.add_at(&self.path, Rule::Forbidden(String::from(pattern)));
            }
            if !entry.contains(PLUGIN_SEPARATOR) {
                findings.add_at(&self.path, Rule::HandWrittenCommand);
            }
        }
    }
}

impl Findings {
    fn add_at(&mut self, path: &str, rule: Rule) {
        self.items.insert(Finding::whole_file(path, rule));
    }

    pub(crate) fn add(&mut self, relative: &str, rule: Rule) {
        self.items.insert(Finding::whole_file(
            &format!("{TAURI_DIRECTORY}/{relative}"),
            rule,
        ));
    }
}

fn list_names(directory: &Path) -> Result<Vec<(String, fs::FileType)>, String> {
    let listing =
        fs::read_dir(directory).map_err(|error| format!("{}: {error}", directory.display()))?;
    let mut names = Vec::new();
    for listed in listing {
        let entry = listed.map_err(|error| format!("{}: {error}", directory.display()))?;
        let file_type = entry
            .file_type()
            .map_err(|error| format!("{}: {error}", entry.path().display()))?;
        names.push((entry.file_name().to_string_lossy().into_owned(), file_type));
    }
    names.sort_by(|left, right| left.0.cmp(&right.0));
    Ok(names)
}

fn read_json(directory: &Path, relative: &str, findings: &mut Findings) -> Option<Json> {
    let text = fs::read_to_string(directory.join(relative)).ok()?;
    let parsed = parse(&text);
    if parsed.is_none() {
        findings.add(relative, Rule::Unparsable);
    }
    parsed
}

fn config_findings(directory: &Path, findings: &mut Findings) -> Result<(), String> {
    for (name, _) in list_names(directory)? {
        let lowered = name.to_lowercase();
        if lowered.starts_with(CONFIG_PREFIX) && name != CONFIG_FILE {
            findings.add(&name, Rule::ExtraConfig);
        }
    }
    let Some(config) = read_json(directory, CONFIG_FILE, findings) else {
        findings.add(CONFIG_FILE, Rule::NotExplicit);
        return Ok(());
    };
    let listed = config
        .get("app")
        .and_then(|app| app.get("security"))
        .and_then(|security| security.get("capabilities"))
        .and_then(Json::as_array);
    match listed {
        Some(list) if !list.is_empty() => {
            if list != [Json::Text(String::from(MAIN_CAPABILITY))].as_slice() {
                findings.add(CONFIG_FILE, Rule::ListNotMain);
            }
        }
        Some(_) | None => findings.add(CONFIG_FILE, Rule::NotExplicit),
    }
    Ok(())
}

fn permission_identifier(entry: &Json) -> Option<&str> {
    entry
        .as_str()
        .or_else(|| entry.get("identifier").and_then(Json::as_str))
}

fn forbidden_pattern(identifier: &str) -> Option<&'static str> {
    FORBIDDEN_PERMISSIONS.into_iter().find(|pattern| {
        pattern
            .strip_suffix('*')
            .map_or(*pattern == identifier, |prefix| {
                identifier.starts_with(prefix)
            })
    })
}

fn permission_findings(
    relative: &str,
    permissions: &[Json],
    allowed: &AllowedPermissions,
    findings: &mut Findings,
) {
    let mut referenced = BTreeSet::new();
    for entry in permissions {
        let Some(identifier) = permission_identifier(entry) else {
            findings.add(relative, Rule::Unparsable);
            continue;
        };
        if !identifier.contains(PLUGIN_SEPARATOR) && identifier != COMMAND_SET {
            findings.add(relative, Rule::HandWrittenCommand);
        } else if identifier != COMMAND_SET && !allowed.entries.contains(identifier) {
            findings.add(relative, Rule::NotAllowed);
        }
        referenced.insert(identifier);
    }
    if !referenced.contains(COMMAND_SET) {
        findings.add(relative, Rule::CommandSetNotReferenced);
    }
}

fn capability_findings(
    directory: &Path,
    allowed: &AllowedPermissions,
    findings: &mut Findings,
) -> Result<(), String> {
    let folder = directory.join(CAPABILITIES_DIRECTORY);
    let relative = format!("{CAPABILITIES_DIRECTORY}/{MAIN_CAPABILITY_FILE}");
    if folder.is_dir() {
        for (name, _) in list_names(&folder)? {
            if name != MAIN_CAPABILITY_FILE {
                findings.add(
                    &format!("{CAPABILITIES_DIRECTORY}/{name}"),
                    Rule::ExtraCapabilityFile,
                );
            }
        }
    }
    if !directory.join(&relative).is_file() {
        findings.add(&relative, Rule::MainMissing);
        return Ok(());
    }
    let Some(capability) = read_json(directory, &relative, findings) else {
        return Ok(());
    };
    if capability.get("identifier").and_then(Json::as_str) != Some(MAIN_CAPABILITY) {
        findings.add(&relative, Rule::Identifier);
    }
    let windows = capability.get("windows").and_then(Json::as_array);
    if windows != Some([Json::Text(String::from(MAIN_CAPABILITY))].as_slice())
        || capability.get("webviews").is_some()
    {
        findings.add(&relative, Rule::Windows);
    }
    if capability.get("remote").is_some() {
        findings.add(&relative, Rule::Remote);
    }
    match capability.get("permissions").and_then(Json::as_array) {
        Some(permissions) => permission_findings(&relative, permissions, allowed, findings),
        None => findings.add(&relative, Rule::Unparsable),
    }
    Ok(())
}

pub(super) fn valid_command(name: &str) -> bool {
    name.starts_with(|first: char| first.is_ascii_lowercase())
        && name
            .chars()
            .all(|next| next.is_ascii_lowercase() || next.is_ascii_digit() || next == '_')
}

fn command_list(directory: &Path, findings: &mut Findings) -> Vec<String> {
    let Ok(text) = fs::read_to_string(directory.join(COMMAND_LIST_FILE)) else {
        findings.add(COMMAND_LIST_FILE, Rule::CommandListFormat);
        return Vec::new();
    };
    let commands: Vec<String> = text.lines().map(String::from).collect();
    let mut previous: Option<&str> = None;
    let mut ordered = true;
    for command in &commands {
        ordered = ordered && valid_command(command) && previous < Some(command.as_str());
        previous = Some(command.as_str());
    }
    if !ordered || !(text.is_empty() || text.ends_with('\n')) {
        findings.add(COMMAND_LIST_FILE, Rule::CommandListFormat);
    }
    commands
}

fn command_permission(command: &str) -> String {
    format!("{COMMAND_PERMISSION_PREFIX}{}", command.replace('_', "-"))
}

fn command_set_permissions(table: &toml::Table) -> Option<Vec<String>> {
    let [entry] = table.get("set")?.as_array()?.as_slice() else {
        return None;
    };
    let set = entry.as_table()?;
    let known = set
        .keys()
        .all(|key| ["identifier", "description", "permissions"].contains(&key.as_str()));
    if table.len() != 1 || !known || set.get("identifier")?.as_str() != Some(COMMAND_SET) {
        return None;
    }
    set.get("permissions")?
        .as_array()?
        .iter()
        .map(|permission| permission.as_str().map(String::from))
        .collect()
}

fn command_set_findings(directory: &Path, commands: &[String], findings: &mut Findings) {
    let relative = format!("{PERMISSIONS_DIRECTORY}/{COMMAND_SET_FILE}");
    let Ok(text) = fs::read_to_string(directory.join(&relative)) else {
        findings.add(&relative, Rule::CommandSetShape);
        return;
    };
    let Ok(table) = text.parse::<toml::Table>() else {
        findings.add(&relative, Rule::Unparsable);
        return;
    };
    let Some(permissions) = command_set_permissions(&table) else {
        findings.add(&relative, Rule::CommandSetShape);
        return;
    };
    let expected: Vec<String> = commands
        .iter()
        .map(|command| command_permission(command))
        .collect();
    if permissions != expected {
        findings.add(&relative, Rule::CommandMismatch);
    }
}

fn autogenerated_findings(
    folder: &Path,
    relative: &str,
    commands: &[String],
    findings: &mut Findings,
) -> Result<(), String> {
    let generated: BTreeSet<String> = commands
        .iter()
        .map(|command| format!("{command}.toml"))
        .collect();
    for (inner, inner_type) in list_names(folder)? {
        if !generated.contains(&inner) || inner_type.is_dir() || inner_type.is_symlink() {
            findings.add(&format!("{relative}/{inner}"), Rule::ExtraPermissionFile);
        }
    }
    Ok(())
}

fn permission_directory_findings(
    directory: &Path,
    commands: &[String],
    findings: &mut Findings,
) -> Result<(), String> {
    let folder = directory.join(PERMISSIONS_DIRECTORY);
    if !folder.is_dir() {
        return Ok(());
    }
    for (name, file_type) in list_names(&folder)? {
        let relative = format!("{PERMISSIONS_DIRECTORY}/{name}");
        if name == AUTOGENERATED_DIRECTORY && file_type.is_dir() && !file_type.is_symlink() {
            autogenerated_findings(&folder.join(&name), &relative, commands, findings)?;
        } else if name != COMMAND_SET_FILE || file_type.is_dir() || file_type.is_symlink() {
            findings.add(&relative, Rule::ExtraPermissionFile);
        }
    }
    Ok(())
}

pub(crate) fn check_tauri_directory(
    directory: &Path,
    allowed: &AllowedPermissions,
) -> Result<BTreeSet<Finding<Rule>>, String> {
    let mut findings = Findings {
        items: BTreeSet::new(),
    };
    allowed.findings(&mut findings);
    config_findings(directory, &mut findings)?;
    capability_findings(directory, allowed, &mut findings)?;
    let commands = command_list(directory, &mut findings);
    command_set_findings(directory, &commands, &mut findings);
    permission_directory_findings(directory, &commands, &mut findings)?;
    build_script_findings(directory, &commands, &mut findings);
    Ok(findings.items)
}

pub(crate) fn command() -> ExitCode {
    report(
        "capability-check",
        workspace_root().and_then(|root| {
            check_tauri_directory(
                &root.join(TAURI_DIRECTORY),
                &AllowedPermissions::load(&root)?,
            )
        }),
    )
}
