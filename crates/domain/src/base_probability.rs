    fn rescaled_days_for_equal_variance(
        sigma: Number,
        days: Number,
        sample_sigma: Number,
    ) -> Number {
        let time_variance = sigma
            .0
            .checked_mul(sigma.0)
            .and_then(|variance| variance.checked_mul(days.0))
            .expect("독립 시간분산");
        let sample_variance = sample_sigma
            .0
            .checked_mul(sample_sigma.0)
            .expect("새 일간 분산");
        Number(
            time_variance
                .checked_div(sample_variance)
                .expect("같은 시간분산의 H"),
        )
    }
